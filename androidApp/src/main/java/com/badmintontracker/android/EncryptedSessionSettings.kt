package com.badmintontracker.android

import android.content.Context
import android.content.SharedPreferences
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import com.russhwolf.settings.Settings
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Android Keystore AES-256-GCM encrypted [Settings] store for auth session material.
 *
 * Backed by a dedicated private [SharedPreferences] file (`rally_session_enc`) so
 * the Supabase session and PKCE verifier never sit in plaintext in `rally.xml`.
 * Each write encrypts with a fresh random 12-byte GCM IV generated by the Keystore
 * cipher, prepends the IV to the ciphertext+tag, and stores it Base64-encoded.
 */
class EncryptedSessionSettings(
    context: Context,
    prefsName: String = PREFS_NAME,
) : Settings {

    private val prefs: SharedPreferences =
        context.applicationContext.getSharedPreferences(prefsName, Context.MODE_PRIVATE)

    override val keys: Set<String>
        get() = prefs.all.keys

    override val size: Int
        get() = prefs.all.size

    override fun clear() {
        prefs.edit().clear().apply()
    }

    override fun remove(key: String) {
        prefs.edit().remove(key).apply()
    }

    override fun hasKey(key: String): Boolean = prefs.contains(key)

    override fun putInt(key: String, value: Int) = putString(key, value.toString())

    override fun getInt(key: String, defaultValue: Int): Int =
        getIntOrNull(key) ?: defaultValue

    override fun getIntOrNull(key: String): Int? =
        getStringOrNull(key)?.toIntOrNull()

    override fun putLong(key: String, value: Long) = putString(key, value.toString())

    override fun getLong(key: String, defaultValue: Long): Long =
        getLongOrNull(key) ?: defaultValue

    override fun getLongOrNull(key: String): Long? =
        getStringOrNull(key)?.toLongOrNull()

    override fun putString(key: String, value: String) {
        val encrypted = encrypt(value)
        prefs.edit().putString(key, encrypted).apply()
    }

    override fun getString(key: String, defaultValue: String): String =
        getStringOrNull(key) ?: defaultValue

    override fun getStringOrNull(key: String): String? {
        val encoded = prefs.getString(key, null) ?: return null
        return runCatching { decrypt(encoded) }.getOrNull()
    }

    override fun putFloat(key: String, value: Float) = putString(key, value.toString())

    override fun getFloat(key: String, defaultValue: Float): Float =
        getFloatOrNull(key) ?: defaultValue

    override fun getFloatOrNull(key: String): Float? =
        getStringOrNull(key)?.toFloatOrNull()

    override fun putDouble(key: String, value: Double) = putString(key, value.toString())

    override fun getDouble(key: String, defaultValue: Double): Double =
        getDoubleOrNull(key) ?: defaultValue

    override fun getDoubleOrNull(key: String): Double? =
        getStringOrNull(key)?.toDoubleOrNull()

    override fun putBoolean(key: String, value: Boolean) = putString(key, value.toString())

    override fun getBoolean(key: String, defaultValue: Boolean): Boolean =
        getBooleanOrNull(key) ?: defaultValue

    override fun getBooleanOrNull(key: String): Boolean? =
        getStringOrNull(key)?.toBooleanStrictOrNull()

    private fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey())
        val iv = cipher.iv
        require(iv != null && iv.size == GCM_IV_LENGTH) {
            "unexpected GCM IV length ${iv?.size}"
        }
        val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        val combined = ByteArray(GCM_IV_LENGTH + ciphertext.size)
        iv.copyInto(combined, destinationOffset = 0)
        ciphertext.copyInto(combined, destinationOffset = GCM_IV_LENGTH)
        return Base64.encodeToString(combined, Base64.NO_WRAP)
    }

    private fun decrypt(encoded: String): String {
        val combined = Base64.decode(encoded, Base64.NO_WRAP)
        require(combined.size > GCM_IV_LENGTH) { "ciphertext truncated" }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        val spec = GCMParameterSpec(GCM_TAG_BITS, combined, 0, GCM_IV_LENGTH)
        cipher.init(Cipher.DECRYPT_MODE, secretKey(), spec)
        val plaintext = cipher.doFinal(combined, GCM_IV_LENGTH, combined.size - GCM_IV_LENGTH)
        return plaintext.toString(Charsets.UTF_8)
    }

    private fun secretKey(): SecretKey {
        loadExistingKey()?.let { return it }
        synchronized(keyLock) {
            loadExistingKey()?.let { return it }
            val spec = KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                .build()
            return KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
                .apply { init(spec) }
                .generateKey()
        }
    }

    private fun loadExistingKey(): SecretKey? {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        return keyStore.getKey(KEY_ALIAS, null) as? SecretKey
    }

    private companion object {
        const val PREFS_NAME = "rally_session_enc"
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "com.badmintontracker.android.session_key"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val KEY_SIZE_BITS = 256
        const val GCM_IV_LENGTH = 12
        const val GCM_TAG_BITS = 128

        val keyLock = Any()
    }
}
